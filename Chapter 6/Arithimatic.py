# there are seven type of arithimatic operators.

a = 10
b = 20
c = 7.9
d = "Hello"
e = "World"
f = (1,2)
f1= (3,4)
g = [1,2]
g1 = [3,4]

# Addition + : this is use to add the value and work on datatypes like Int, float, string, list, tuple.
print("addition +")
print(a + b)  # 30 Int
print(a + c)  # 17.9 float
print(d + e)  # HelloWorld String
print(f + f1) # (1, 2, 3, 4) Tuple
print(g + g1) # [1, 2, 3, 4] List

# Subtraction - : this is use to subtract the value and work on datatypes like Int, float.
print("\nsubtraction -")
print(a - b)  # -10 Int
print(a - c)  # 2.1 float

# Multiplication * : this is use to multiply the value and work on datatypes like Int, float, string, list, tuple.
print("\nmultiplication *")
print(a * b)  # 200 Int
print(a * c)  # 79.0 float
print(d * 2)  # HelloWorldHelloWorld String
print(f * 2)  # (1, 2, 1, 2) Tuple
print(g * 2)  # [1, 2, 1, 2] List

# Division / : this is use to divide the value and work on datatypes like Int, float.
print("\ndivision /")
print(a / b)  # 0.5 float
print(a / c)  # 1.2658227848101266 float

# Floor Division // : this is use to divide the value and work on datatypes like Int, float.
print("\nfloor division //")
print(a // b)  # 0 Int
print(a // c)  # 1 Int

# Modulus % : this is use to find the remainder and work on datatypes like Int, float.
print("\nmodulus %")
print(a % b)  # 10 Int
print(a % c)  # 2.1 float

# Exponentiation ** : this is use to find the power and work on datatypes like Int, float.
print("\nexponentiation **")
print(a ** b)  # 100000000000000000000 Int
print(a ** c)  # 6813.780172970392 float



